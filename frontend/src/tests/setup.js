import '@testing-library/jest-dom/vitest'

// jsdom no implementa matchMedia; react-bootstrap (Offcanvas) lo usa para breakpoints.
if (typeof window !== 'undefined' && !window.matchMedia) {
  window.matchMedia = (query) => ({
    matches: false,
    media: query,
    onchange: null,
    addListener: () => {},
    removeListener: () => {},
    addEventListener: () => {},
    removeEventListener: () => {},
    dispatchEvent: () => false,
  })
}
